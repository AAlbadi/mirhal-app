interface I18nContextValue {
  lang: Language;
  dir: 'ltr' | 'rtl';
  t: (key: keyof typeof translations, params?: Record<string, string | number>) => string;
  setLang: (lang: Language) => void;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLang] = useState<Language>(() => {
    const saved = typeof window !== 'undefined' ? window.localStorage.getItem('lang') : null;
    return (saved === 'ar' || saved === 'en') ? (saved as Language) : 'en';
  });

  const dir: 'ltr' | 'rtl' = lang === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    if (typeof window !== 'undefined') {
      window.localStorage.setItem('lang', lang);
      document.documentElement.setAttribute('dir', dir);
      document.documentElement.setAttribute('lang', lang);

      // Set font family based on language
      if (lang === 'ar') {
        document.documentElement.style.fontFamily = 'Arabic-Custom, sans-serif';
        document.body.classList.add('font-arabic');
        document.body.classList.remove('font-sans');
      } else {
        document.documentElement.style.fontFamily = 'Urbanist, sans-serif';
        document.body.classList.add('font-sans');
        document.body.classList.remove('font-arabic');
      }
    }
  }, [lang, dir]);

  const t = useMemo(() => (key: keyof typeof translations, params?: Record<string, string | number>) => {
    let text = translations[key]?.[lang] || key;
    if (params) {
      Object.entries(params).forEach(([paramKey, paramValue]) => {
        text = text.replace(new RegExp(`{${paramKey}}`, 'g'), String(paramValue));
      });
    }
    return text;
  }, [lang]);

  const value = useMemo(() => ({ lang, dir, t, setLang }), [lang, dir, t]);

  return (
    <I18nContext.Provider value={value}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = (): I18nContextValue => {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
};


